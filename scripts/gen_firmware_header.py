#!/usr/bin/env python3
"""Fetch (or reuse) QCA Rome 3.2 USB firmware, verify SHA-256, emit a C header.

Usage: gen_firmware_header.py <out.h> [--cache DIR]
Pinned to linux-firmware commit d0039fd797d7776d89f00c22c45754914a96706e.
"""
import argparse, hashlib, pathlib, urllib.request

COMMIT = "d0039fd797d7776d89f00c22c45754914a96706e"
MIRRORS = [
    f"https://gitlab.com/kernel-firmware/linux-firmware/-/raw/{COMMIT}/{{}}",
    f"https://git.kernel.org/pub/scm/linux/kernel/git/firmware/linux-firmware.git/plain/{{}}?id={COMMIT}",
]
FILES = {
    "qca/rampatch_usb_00000302.bin": ("qca_rampatch_usb_00000302", 68644,
        "f0d15f6d7c4ce17270c951287222699c0909bea9028ecb84d2e8be6fa364691e"),
    "qca/nvm_usb_00000302.bin": ("qca_nvm_usb_00000302", 1998,
        "9ee2cff5bd51523b65c941b72ecf05a8b5e7b9e280c79fa08c70ade7205088a5"),
}

def fetch(path, cache):
    local = cache / pathlib.Path(path).name
    if not local.exists():
        cache.mkdir(parents=True, exist_ok=True)
        last = None
        for base in MIRRORS:
            try:
                req = urllib.request.Request(base.format(path), headers={"User-Agent": "Mozilla/5.0"})
                with urllib.request.urlopen(req, timeout=60) as r:
                    local.write_bytes(r.read())
                break
            except Exception as e:  # try next mirror; hash is checked by caller
                last = e
        else:
            raise SystemExit(f"{path}: all mirrors failed: {last}")
    return local.read_bytes()

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("--cache", default="build/firmware-cache")
    a = ap.parse_args()
    cache = pathlib.Path(a.cache)
    lines = ["// Generated by scripts/gen_firmware_header.py. Do not edit.",
             f"// Source: linux-firmware {COMMIT}; licence: LICENSE.QualcommAtheros_ath10k + NOTICE.qca",
             "#pragma once", "#include <stddef.h>", "#include <stdint.h>"]
    for path, (sym, size, digest) in FILES.items():
        data = fetch(path, cache)
        got = hashlib.sha256(data).hexdigest()
        if len(data) != size or got != digest:
            raise SystemExit(f"{path}: size {len(data)} sha256 {got} does not match pinned {size} {digest}")
        lines.append(f"static const uint8_t {sym}[{size}] = {{")
        for i in range(0, size, 16):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i+16]) + ",")
        lines += ["};", f"static const size_t {sym}_len = {size};"]
        print(f"OK {path} {size} {got}")
    out = pathlib.Path(a.out); out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")

if __name__ == "__main__":
    main()
